#!/usr/bin/env node
/*
 * build-palette.js — generate src/catalogs/colors.js from the real Tailwind package.
 *
 * The color control and hyperclay's AI add-cms both need the Tailwind palette, so
 * it is generated from the pinned tailwindcss tarball rather than typed by hand or
 * fetched at page runtime. Black and white are not part of a hue/shade grid and are
 * deliberately left out.
 *
 * Run: npm run build:palette  (needs network access to the npm registry).
 */
import fs from 'fs'
import os from 'os'
import path from 'path'
import { execFileSync } from 'child_process'
import { fileURLToPath } from 'url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const root = path.join(__dirname, '..')

const TAILWIND_VERSION = '4.3.3'
const SHADES = ['50', '100', '200', '300', '400', '500', '600', '700', '800', '900', '950']
const EXPECTED_HUES = 26

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'hcms-palette-'))

try {
  execFileSync(
    'npm',
    ['pack', `tailwindcss@${TAILWIND_VERSION}`, '--min-release-age=0', '--pack-destination', tmp],
    { stdio: ['ignore', 'pipe', 'inherit'] }
  )
  const tgz = fs.readdirSync(tmp).find((name) => name.endsWith('.tgz'))
  if (!tgz) throw new Error('npm pack produced no tarball in ' + tmp)
  execFileSync('tar', ['xzf', path.join(tmp, tgz), '-C', tmp])

  const themeCss = fs.readFileSync(path.join(tmp, 'package', 'theme.css'), 'utf8')

  const hues = []
  const byHue = new Map()
  const pattern = /--color-([a-z]+)-(\d+):\s*([^;]+);/g
  let match
  while ((match = pattern.exec(themeCss))) {
    const [, hue, shade, value] = match
    if (!SHADES.includes(shade)) continue
    if (!byHue.has(hue)) {
      byHue.set(hue, new Map())
      hues.push(hue)
    }
    byHue.get(hue).set(shade, value.trim())
  }

  if (hues.length !== EXPECTED_HUES) {
    throw new Error(`expected ${EXPECTED_HUES} hues, found ${hues.length}: ${hues.join(', ')}`)
  }
  for (const hue of hues) {
    const shadeMap = byHue.get(hue)
    const missing = SHADES.filter((shade) => !shadeMap.has(shade))
    if (missing.length) throw new Error(`hue ${hue} is missing shades: ${missing.join(', ')}`)
  }

  const colors = []
  for (const hue of hues) {
    for (const shade of SHADES) {
      colors.push({ id: `${hue}-${shade}`, hue, shade, value: byHue.get(hue).get(shade) })
    }
  }

  const quote = (value) => `'${String(value).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`
  const lines = [
    `// Generated by scripts/build-palette.js from tailwindcss@${TAILWIND_VERSION} (MIT, Tailwind Labs).`,
    '// Do not edit by hand: change the pinned version in the script and rerun it.',
    `export const PALETTE_SOURCE = 'tailwindcss@${TAILWIND_VERSION}'`,
    `export const SHADES = [${SHADES.map(quote).join(', ')}]`,
    `export const HUES = [${hues.map(quote).join(', ')}]`,
    'export const COLORS = Object.freeze([',
    ...colors.map(
      (c) => `  { id: ${quote(c.id)}, hue: ${quote(c.hue)}, shade: ${quote(c.shade)}, value: ${quote(c.value)} },`
    ),
    '])',
    '',
  ]

  const outDir = path.join(root, 'src', 'catalogs')
  fs.mkdirSync(outDir, { recursive: true })
  fs.writeFileSync(path.join(outDir, 'colors.js'), lines.join('\n'))

  console.log(`build-palette: ${hues.length} hues, ${colors.length} colors -> src/catalogs/colors.js`)
} finally {
  fs.rmSync(tmp, { recursive: true, force: true })
}
